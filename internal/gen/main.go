// Command gen generates internal/metrics_gen.go and internal/collect_gen.go
// from the single metric table in table.go. Run via `go generate ./internal/...`
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

const header = `// Code generated by internal/gen from table.go; DO NOT EDIT.
// SPDX-License-Identifier: MIT
// Copyright (C) 2026 Tizian Bahr

`

func main() {
	out := flag.String("out", ".", "directory to write metrics_gen.go and collect_gen.go into")
	flag.Parse()

	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(out string) error {
	if err := validate(); err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o750); err != nil {
		return err
	}
	if err := writeGoFile(filepath.Join(out, "metrics_gen.go"), genMetrics()); err != nil {
		return err
	}
	if err := writeGoFile(filepath.Join(out, "collect_gen.go"), genCollect()); err != nil {
		return err
	}
	return nil
}

// validate catches the two mistakes a hand-edited table row can make: a
// duplicate identifier/path, and a group not declared in groupOrder. Anything
// else (a protoField that doesn't exist on the target message) is caught by
// the Go compiler when it builds the generated collect_gen.go.
func validate() error {
	names := make(map[string]bool, len(metrics))
	paths := make(map[string]bool, len(metrics))
	groups := make(map[string]bool, len(groupOrder))
	for _, g := range groupOrder {
		groups[g.group] = true
	}

	for _, m := range metrics {
		if names[m.name] {
			return fmt.Errorf("duplicate metric name %q", m.name)
		}
		names[m.name] = true

		if paths[m.path] {
			return fmt.Errorf("duplicate metric path %q", m.path)
		}
		paths[m.path] = true

		if !groups[m.group] {
			return fmt.Errorf("metric %q: unknown group %q (add it to groupOrder)", m.name, m.group)
		}
	}
	return nil
}

func writeGoFile(name string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("formatting %s: %w\n---\n%s", name, err, src)
	}
	// #nosec G306 -- generated Go source, world-readable is fine
	return os.WriteFile(name, formatted, 0o644)
}

// vFunc names the sampleCollector method (vUint, vFloat, vUint32, vHist)
// that reads a metric of this kind.
func (k kind) vFunc() string {
	switch k {
	case kindUint64:
		return "vUint"
	case kindUint32:
		return "vUint32"
	case kindFloat64:
		return "vFloat"
	case kindHistogram:
		return "vHist"
	default:
		panic(fmt.Sprintf("unknown kind %d", k))
	}
}

func genMetrics() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package internal\n\n")

	b.WriteString("// Metric identifies one collected runtime/metrics value. Each constant is a\n")
	b.WriteString("// direct index into AllMetricNames, so looking up a metric's current value is\n")
	b.WriteString("// an O(1) array access with no string hashing.\n")
	b.WriteString("type Metric uint8\n\n")

	b.WriteString("const (\n")
	lastGroup := ""
	for i, m := range metrics {
		if m.group != lastGroup && i > 0 {
			b.WriteString("\n")
		}
		lastGroup = m.group
		if i == 0 {
			fmt.Fprintf(&b, "\tMetric%s Metric = iota\n", m.name)
		} else {
			fmt.Fprintf(&b, "\tMetric%s\n", m.name)
		}
	}
	b.WriteString("\n\tmetricCount\n")
	b.WriteString(")\n\n")

	b.WriteString("// AllMetricNames maps each Metric index constant to its runtime/metrics path.\n")
	b.WriteString("// Keys are the index constants themselves, so a duplicate or out-of-range\n")
	b.WriteString("// index is a compile error rather than a silently wrong lookup.\n")
	b.WriteString("var AllMetricNames = [metricCount]string{\n")
	lastGroup = ""
	for i, m := range metrics {
		if m.group != lastGroup && i > 0 {
			b.WriteString("\n")
		}
		lastGroup = m.group
		fmt.Fprintf(&b, "\tMetric%s: %q,\n", m.name, m.path)
	}
	b.WriteString("}\n\n")

	b.WriteString("// histogramMetrics lists every histogram-kind metric, in table order.\n")
	b.WriteString("var histogramMetrics = []Metric{\n")
	for _, m := range metrics {
		if m.kind == kindHistogram {
			fmt.Fprintf(&b, "\tMetric%s,\n", m.name)
		}
	}
	b.WriteString("}\n")

	return b.Bytes()
}

func genCollect() []byte {
	byGroup := make(map[string][]field, len(groupOrder))
	for _, m := range metrics {
		byGroup[m.group] = append(byGroup[m.group], m)
	}

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package internal\n\n")
	fmt.Fprintf(&b, "import %q\n\n", "github.com/TB004/pprof-viz-collector/internal/proto")

	b.WriteString("// buildAllResponse maps every metric in the table (table.go) into a\n")
	b.WriteString("// proto.AllResponse using c's read/diff helpers.\n")
	b.WriteString("//\n")
	b.WriteString("// A metric with no entry here is a compile error, not a silently dropped\n")
	b.WriteString("// value.\n")
	b.WriteString("func buildAllResponse(c *sampleCollector) *proto.AllResponse {\n")
	b.WriteString("\treturn &proto.AllResponse{\n")
	for _, g := range groupOrder {
		fields := byGroup[g.group]
		if len(fields) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t\t%s: &proto.%s{\n", g.group, g.message)
		for _, m := range fields {
			fmt.Fprintf(&b, "\t\t\t%s: c.%s(Metric%s),\n", m.protoField, m.kind.vFunc(), m.name)
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")

	return b.Bytes()
}
